import sharp from 'sharp';
import {mkdir,copyFile,readFile,writeFile} from 'node:fs/promises';

// One editable emblem is shared by every size; no separate face drawing.
const source='packages/design-tokens/brand';
const master=await readFile(`${source}/kingfisher.svg`,'utf8');
const {version}=JSON.parse(await readFile('package.json','utf8'));
const definitions=master.match(/<defs>([\s\S]*?)<\/defs>/)?.[1];
const mark=master.match(/<g id="canonical-mark">([\s\S]*?)<\/g>/)?.[1].trim();
const eye=mark?.match(/<circle id="eye"[^>]*\/>/)?.[0];
const throat=mark?.match(/<path id="throat"[^>]*\/>/)?.[0];
if(!definitions||!mark||!eye||!throat)throw new Error('Canonical kingfisher mark missing');
const viewport='40 40 448 448';
const compact=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewport}" fill="none"><title>Alcydeo — martin-pêcheur</title><desc>Le même emblème original à toutes les tailles, sans détourage.</desc><!-- Generated by scripts/brand.mjs; edit kingfisher.svg. --><defs>${definitions}</defs><g>${mark}</g></svg>\n`;
const holes=eye.replace(/fill="[^"]*"/,'fill="#000000"')+throat.replace(/fill="[^"]*"/,'fill="#000000"');
const mono=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewport}"><title>Alcydeo — martin-pêcheur monochrome</title><defs>${definitions}<mask id="mark-mask" maskUnits="userSpaceOnUse" x="40" y="40" width="448" height="448" style="mask-type:luminance"><use href="#silhouette" fill="#FFFFFF"/>${holes}</mask></defs><path d="M40 40H488V488H40Z" fill="currentColor" mask="url(#mark-mask)" /></svg>\n`;
await writeFile(`${source}/kingfisher-icon.svg`,compact);
await writeFile(`${source}/kingfisher-mono.svg`,mono);
const lettering=await readFile(`${source}/wordmark-type.svg`,'utf8');
const image=svg=>`data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
const letterPaths=lettering.match(/<g fill="currentColor">([\s\S]*?)<\/g>/)?.[1];
if(!letterPaths)throw new Error('Outlined Alcydeo lettering missing');
const placedBird=(x,y,size)=>`<image href="${image(master)}" x="${x}" y="${y}" width="${size}" height="${size}"/>`;
const placedType=(x,y,scale,color)=>`<g fill="${color}" transform="translate(${x} ${y}) scale(${scale})">${letterPaths}</g>`;
const wordmark=color=>`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 360"><title>Alcydeo</title>${placedBird(16,16,328)}${placedType(390,84,1.1,color)}</svg>`;
const stacked=color=>`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 800"><title>Alcydeo</title>${placedBird(156,36,488)}${placedType(130,555,.8,color)}</svg>`;
const social=(background,color)=>`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 900"><title>Alcydeo</title><rect width="1600" height="900" fill="${background}"/>${placedBird(100,140,580)}${placedType(740,330,1.05,color)}</svg>`;
